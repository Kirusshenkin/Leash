//! Сравнение текста со страницы со списками слов. Страница не должна прятать
//! слово от проверки невидимым символом, диакритикой, буквой другого алфавита
//! того же вида или полноширинной формой.

/// Есть ли в тексте хотя бы одно слово из списка (сравнение по «скелету»).
pub(crate) fn contains_any(haystack: &str, needles: &[&str]) -> bool {
    let h = skeleton(haystack);
    needles.iter().any(|n| h.contains(&skeleton(n)))
}

/// Нижний регистр без невидимых символов и комбинирующих знаков; похожие
/// буквы кириллицы и греческого сведены к латинским, пробелы — к одному.
pub(crate) fn skeleton(s: &str) -> String {
    let mut out = String::with_capacity(s.len());
    let mut space = false;
    for c in s.chars().flat_map(char::to_lowercase) {
        let c = match c {
            '\u{00AD}'
            | '\u{034F}'
            | '\u{061C}'
            | '\u{115F}'
            | '\u{1160}'
            | '\u{17B4}'
            | '\u{17B5}'
            | '\u{180B}'..='\u{180F}'
            | '\u{200B}'..='\u{200F}'
            | '\u{202A}'..='\u{202E}'
            | '\u{2060}'..='\u{206F}'
            | '\u{3164}'
            | '\u{FE00}'..='\u{FE0F}'
            | '\u{FEFF}'
            | '\u{FFA0}'
            | '\u{E0000}'..='\u{E0FFF}'
            | '\u{0300}'..='\u{036F}'
            | '\u{0483}'..='\u{0489}'
            | '\u{1AB0}'..='\u{1AFF}'
            | '\u{1DC0}'..='\u{1DFF}'
            | '\u{20D0}'..='\u{20FF}'
            | '\u{FE20}'..='\u{FE2F}' => continue,
            '\u{FF01}'..='\u{FF5E}' => char::from_u32(c as u32 - 0xFEE0).unwrap_or(c),
            'а' | 'α' => 'a',
            'в' | 'β' => 'b',
            'с' | 'ς' => 'c',
            'е' | 'ё' | 'є' | 'ε' => 'e',
            'һ' => 'h',
            'і' | 'ї' | 'ı' | 'ι' | 'ӏ' => 'i',
            'ј' => 'j',
            'к' | 'κ' => 'k',
            'м' => 'm',
            'н' | 'η' => 'n',
            'о' | 'ο' | '0' => 'o',
            'р' | 'ρ' => 'p',
            'ԛ' => 'q',
            'ѕ' => 's',
            'т' | 'τ' => 't',
            'у' | 'υ' | 'γ' => 'y',
            'х' | 'χ' => 'x',
            'ԝ' | 'ѡ' => 'w',
            'ь' => 'b',
            c if c.is_whitespace() => ' ',
            c => c,
        };
        if c == ' ' {
            if !space {
                out.push(' ');
            }
            space = true;
        } else {
            out.push(c);
            space = false;
        }
    }
    out
}
